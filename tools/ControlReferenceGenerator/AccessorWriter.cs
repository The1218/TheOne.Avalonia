using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace TheOne.Documentation;

internal static class AccessorWriter
{
    internal static int Write(string root, ContractSet data, bool check)
    {
        var b = new StringBuilder("// <auto-generated/>\n#nullable enable\nnamespace TheOne.DesignPreview.Reference;\n\ninternal static class ContractAccessors\n{\n");
        var entries = data.Types.SelectMany(t => t.Properties.Select(p => (Owner: t, Property: p)))
            .Where(e => (e.Owner.IsControl && !e.Property.Static || e.Property.Attached && e.Property.Target.Length > 0 || e.Owner.Id == "Avalonia.Controls.DataGridColumn")
                && Regex.IsMatch(e.Property.Name, @"^[A-Za-z_]\w*$")).ToArray();
        b.AppendLine("    internal static bool CanRead(string key) => key is");
        b.AppendLine("        " + string.Join(" or\n        ", entries.Select(e => Literal(e.Owner.Id + "." + e.Property.Name))) + ";");
        b.AppendLine("    internal static bool Matches(object target, string key) => (key, target) switch\n    {");
        foreach (var (owner, p) in entries)
            b.AppendLine($"        ({Literal(owner.Id + "." + p.Name)}, global::{(p.Attached ? p.Target : owner.Id)}) => true,");
        b.AppendLine("        _ => false\n    };\n");
        b.AppendLine("    internal static object? Read(object target, string key) => (key, target) switch\n    {");
        foreach (var (owner, p) in entries)
        {
            var target = "global::" + (p.Attached ? p.Target : owner.Id);
            var getter = p.Attached ? $"global::{owner.Id}.Get{p.Name}(instance)" : $"instance.{p.Name}";
            b.AppendLine($"        ({Literal(owner.Id + "." + p.Name)}, {target} instance) => {getter},");
        }
        b.AppendLine("        _ => null\n    };\n");
        b.AppendLine("    internal static bool CanEdit(string key) => key is");
        var editable = entries.Where(e => e.Property.Writable && Parse(e.Property) is not null).ToArray();
        b.AppendLine("        " + string.Join(" or\n        ", editable.Select(e => Literal(e.Owner.Id + "." + e.Property.Name))) + ";");
        b.AppendLine("    internal static bool Set(object target, string key, string value, System.Action<string> log)\n    {\n        switch (key)\n        {");
        var i = 0;
        foreach (var (owner, p) in editable)
        {
            var variable = "instance" + i++;
            var target = "global::" + (p.Attached ? p.Target : owner.Id);
            var setter = p.Attached ? $"global::{owner.Id}.Set{p.Name}({variable}, {Parse(p)})" : $"{variable}.{p.Name} = {Parse(p)}";
            b.AppendLine($"            case {Literal(owner.Id + "." + p.Name)} when target is {target} {variable}: {setter}; return true;");
        }
        b.AppendLine("            default: return false;\n        }\n    }\n");
        b.AppendLine("    internal static bool Restore(object target, string key, object? value)\n    {\n        switch (key)\n        {");
        foreach (var (owner, p) in entries.Where(e => e.Property.Writable))
        {
            var variable = "instance" + i++;
            var target = "global::" + (p.Attached ? p.Target : owner.Id);
            var cast = $"({Qualify(p.Type)})value!";
            var setter = p.Attached ? $"global::{owner.Id}.Set{p.Name}({variable}, {cast})" : $"{variable}.{p.Name} = {cast}";
            b.AppendLine($"            case {Literal(owner.Id + "." + p.Name)} when target is {target} {variable}: {setter}; return true;");
        }
        b.AppendLine("            default: return false;\n        }\n    }\n");
        b.AppendLine("    internal static System.IDisposable Watch(object target, System.Action<string> log)\n    {\n        var detach = new System.Collections.Generic.List<System.Action>();");
        foreach (var owner in data.Types.Where(t => t.IsControl && t.Events.Length > 0))
        {
            var variable = "source" + i++;
            b.AppendLine($"        if (target is global::{owner.Id} {variable})\n        {{");
            foreach (var evt in owner.Events)
            {
                var name = Regex.Match(evt.Signature, @"([A-Za-z_]\w*)$").Value;
                var handler = "handler" + i++;
                var type = Qualify(evt.ValueType.TrimEnd('?'));
                b.AppendLine($"            {type} {handler} = (_, _) => log({Literal(owner.Name + "." + name)});");
                b.AppendLine($"            {variable}.{name} += {handler}; detach.Add(() => {variable}.{name} -= {handler});");
            }
            b.AppendLine("        }");
        }
        b.AppendLine("        return new ExplorerSubscription(() => detach.ForEach(action => action()));\n    }\n}");
        var path = Path.Combine(root, "design/PreviewHost/Reference/ContractAccessors.g.cs");
        var text = b.ToString();
        var equal = File.Exists(path) && File.ReadAllText(path) == text;
        if (check) { Console.WriteLine("Compiled preview accessor drift: " + !equal); return equal ? 0 : 1; }
        Directory.CreateDirectory(Path.GetDirectoryName(path)!); if (!equal) File.WriteAllText(path, text);
        Console.WriteLine($"Generated {entries.Length} compiled property readers, {editable.Length} editors and event subscriptions; no runtime reflection.");
        return 0;
    }

    private static string? Parse(PropertyContract p)
    {
        var type = p.Type.TrimEnd('?');
        string? expression = type switch
        {
            "string" => "value",
            "bool" => "bool.Parse(value)",
            "byte" or "short" or "int" or "long" or "float" or "double" or "decimal" or "uint" or "ulong" or "ushort" => type + ".Parse(value, System.Globalization.CultureInfo.InvariantCulture)",
            "char" => "char.Parse(value)",
            "System.TimeSpan" => "System.TimeSpan.Parse(value, System.Globalization.CultureInfo.InvariantCulture)",
            "System.DateTime" => "System.DateTime.Parse(value, System.Globalization.CultureInfo.InvariantCulture)",
            "System.DateTimeOffset" => "System.DateTimeOffset.Parse(value, System.Globalization.CultureInfo.InvariantCulture)",
            "Avalonia.Thickness" => "global::Avalonia.Thickness.Parse(value)",
            "Avalonia.CornerRadius" => "global::Avalonia.CornerRadius.Parse(value)",
            "Avalonia.Size" => "global::Avalonia.Size.Parse(value)",
            "Avalonia.Media.Color" => "global::Avalonia.Media.Color.Parse(value)",
            "Avalonia.Media.IBrush" or "Avalonia.Media.Brush" => "global::Avalonia.Media.Brush.Parse(value)",
            "Avalonia.Media.Geometry" => "global::Avalonia.Media.Geometry.Parse(value)",
            "Avalonia.Controls.Templates.IDataTemplate" => "new global::Avalonia.Controls.Templates.FuncDataTemplate<object>((item, _) => new global::Avalonia.Controls.TextBlock { Text = value + \" · \" + item?.ToString() })",
            "System.Windows.Input.ICommand" => "new ExplorerCommand(() => log(value))",
            _ => null
        };
        if (p.Choices.Length > 0) expression = $"System.Enum.Parse<global::{type}>(value)";
        if (expression is not null && p.Type.EndsWith('?') && type != "string" && type != "Avalonia.Controls.Templates.IDataTemplate" && type != "System.Windows.Input.ICommand")
            expression = $"string.IsNullOrWhiteSpace(value) ? ({(type.Contains('.') ? "global::" : "") + type}?)null : {expression}";
        return expression;
    }
    private static string Literal(string value) => JsonSerializer.Serialize(value);
    private static string Qualify(string value) => Regex.Replace(value, @"(?<![\w.])(?:TheOne\.Avalonia|Avalonia|System)\.", "global::$0");
}
